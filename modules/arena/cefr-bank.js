/**
 * Returns a flat list of all words in the bank.
 * @returns {Array.<{word: string, def: string, pos: string, tier: string}>}
 */
export function getAllWords() {
  return CEFR_TIERS.flatMap(tier =>
    CEFR_BANK[tier].map(entry => ({ ...entry, tier }))
  );
}

/**
 * Returns words for a given tier or array of tiers.
 * @param {string|string[]} tiers
 * @returns {Array}
 */
export function getWordsForTiers(tiers) {
  const tierList = Array.isArray(tiers) ? tiers : [tiers];
  return tierList.flatMap(t => (CEFR_BANK[t] || []).map(e => ({ ...e, tier: t })));
}

/**
 * Looks up a word's tier entry. Case-insensitive.
 * @param {string} word
 * @returns {{word: string, def: string, pos: string, tier: string}|null}
 */
export function lookupWord(word) {
  const normalized = word.trim().toLowerCase();
  for (const tier of CEFR_TIERS) {
    const found = CEFR_BANK[tier].find(e => e.word.toLowerCase() === normalized);
    if (found) return { ...found, tier };
  }
  return null;
}
